    public function test_summary_returns_complete_data_for_valid_asset(): void
    {
        $service = new UnrealAssetService;

        // Build a minimal valid .uasset with a known class
        $contents = pack('V', 0x9E2A83C1);   // Magic
        $contents .= pack('l', -7);            // Legacy file version
        $contents .= pack('l', 0);             // Legacy UE3 version
        $contents .= pack('l', 1000);          // File version UE4 (5.0)
        $contents .= pack('l', 0);             // File version licensee
        $contents .= str_repeat("\x00", 100);
        $contents .= 'StaticMesh';
        $contents .= str_repeat("\x00", 50);
        $contents .= '/Game/Meshes/SM_Wall';
        $contents .= str_repeat("\x00", 50);

        $summary = $service->summary($contents);

        $this->assertSame('Static Mesh', $summary['asset_class']);
        $this->assertSame('UE 5.0', $summary['engine_version']);
        $this->assertSame(1000, $summary['file_version']);
        $this->assertIsArray($summary['dependencies']);
        $this->assertContains('/Game/Meshes/SM_Wall', $summary['dependencies']);
    }


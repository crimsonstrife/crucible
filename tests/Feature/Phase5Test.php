    public function test_parse_valid_uasset_header(): void
    {
        $service = new UnrealAssetService;

        // Build a minimal valid .uasset header
        $contents = pack('V', 0x9E2A83C1);   // Magic
        $contents .= pack('l', -7);            // Legacy file version
        $contents .= pack('l', 0);             // Legacy UE3 version
        $contents .= pack('l', 522);           // File version UE4 (4.27)
        $contents .= pack('l', 0);             // File version licensee
        $contents .= str_repeat("\x00", 200);  // Padding

        $meta = $service->parse($contents);

        $this->assertNotNull($meta);
        $this->assertTrue($meta['valid']);
        $this->assertSame('0x9E2A83C1', $meta['magic']);
        $this->assertSame(522, $meta['file_version_ue4']);
        $this->assertSame('UE 4.27', $meta['engine_version']);
    }

    public function test_parse_ue5_version_detection(): void
    {
        $service = new UnrealAssetService;

        $contents = pack('V', 0x9E2A83C1);

        $contents .= pack('l', 0);
        $contents .= pack('l', 1004);  // UE 5.2
        $contents .= pack('l', 0);
        $contents .= str_repeat("\x00", 200);

        $meta = $service->parse($contents);

        $this->assertNotNull($meta);
        $this->assertSame('UE 5.2', $meta['engine_version']);
    }


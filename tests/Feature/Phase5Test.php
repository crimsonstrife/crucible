    // ── Engine Version Guessing ─────────────────────────────────────────────

    public function test_guess_engine_version_covers_all_ranges(): void
    {
        $service = new UnrealAssetService;

        // Test via parse (which calls guessEngineVersion internally)
        $versions = [
            0    => 'Unknown',
            503  => 'UE 4.18',
            504  => 'UE 4.19',
            505  => 'UE 4.20',
            508  => 'UE 4.21',
            510  => 'UE 4.22',
            513  => 'UE 4.23',
            514  => 'UE 4.24',
            516  => 'UE 4.25',
            518  => 'UE 4.26',
            522  => 'UE 4.27',
            1000 => 'UE 5.0',
            1002 => 'UE 5.1',
            1004 => 'UE 5.2',
            1007 => 'UE 5.3',
            1008 => 'UE 5.4',
            1009 => 'UE 5.5+',
            1050 => 'UE 5.5+',
        ];

        foreach ($versions as $fileVersion => $expected) {
            $contents = pack('V', 0x9E2A83C1);
            $contents .= pack('l', -7);
            $contents .= pack('l', 0);
            $contents .= pack('l', $fileVersion);
            $contents .= pack('l', 0);
            $contents .= str_repeat("\x00", 200);

            $meta = $service->parse($contents);
            $this->assertNotNull($meta, "parse() returned null for file version {$fileVersion}");
            $this->assertSame($expected, $meta['engine_version'], "Version mismatch for file version {$fileVersion}");
        }
    }
